# ===================================================================
# Python fallback: HookExecutor
# ===================================================================
# This class is used ONLY when Numba is disabled.  It provides a
# unified dispatch loop where CSR plans, njit functions, and Python
# wrappers coexist in a single priority-ordered sequence.
#
# When Numba IS enabled, the compiled path handles dispatch —
# ``CompiledEventHooks.from_compiled_hooks`` generates lifecycle
# wrappers that call CSR and njit hooks directly, including unified
# dispatch for mixed types.  The HookExecutor path is never touched
# in that case.
# ===================================================================


class HookExecutor:
    """Python-layer coordinator for hook execution (Numba-disabled only).

    When Numba is disabled, all hook types (CSR plans, njit functions,
    and Python wrappers) must run through a single sequential path.
    This class holds the descriptors sorted by ``priority`` and
    dispatches each one in order.

    For CSR descriptors, it calls ``execute_csr_event_arrays`` with
    the descriptor's ``plan`` unpacked as individual arrays.  For njit
    and py_wrapper descriptors, it calls them directly.

    .. note::
       In Numba-enabled mode, this executor is never constructed.
       ``BasePopulation.should_use_python_dispatch()`` returns False,
       and the compiled lifecycle wrappers handle everything.
    """

    def __init__(
        self,
        registry: HookProgram,
        hooks_by_event: Dict[int, List[CompiledHookDescriptor]],
    ) -> None:
        """Create an executor with a pre-built registry and descriptor map.

        Args:
            registry: The HookProgram for CSR operations (may be empty
                if there are no declarative hooks).
            hooks_by_event: Descriptors grouped and sorted by event_id
                and priority.  Built by ``from_compiled_hooks``.
        """
        self.registry = registry
        self.hooks_by_event = hooks_by_event

    @staticmethod
    def from_compiled_hooks(
        registry: HookProgram,
        compiled_hooks: List[CompiledHookDescriptor],
    ) -> HookExecutor:
        """Group descriptors by event_id and sort by priority.

        Descriptors without a recognised event_id or without any
        execution payload (plan / njit_fn / py_wrapper all None)
        are silently skipped.
        """
        from collections import defaultdict

        hooks_by_event: Dict[int, List[CompiledHookDescriptor]] = defaultdict(list)
        for desc in compiled_hooks:
            event_id = EVENT_ID_MAP.get(desc.event)
            if event_id is not None:
                # Only include descriptors that have something to execute.
                if desc.plan is not None or desc.njit_fn is not None or desc.py_wrapper is not None:
                    hooks_by_event[event_id].append(desc)

        # Sort each event's descriptors by priority (stable — ties keep
        # registration order).
        for event_id in hooks_by_event:
            hooks_by_event[event_id].sort(key=lambda x: x.priority)

        return HookExecutor(registry, dict(hooks_by_event))

    def execute_event(
        self,
        event_id: int,
        population: BasePopulation[Any],
        tick: int,
        deme_id: int = 0,
    ) -> int:
        """Run all hooks for *event_id* in priority order.

        For each descriptor in the pre-sorted list:

        1. **CSR plan** (``desc.plan is not None``):
           Unpacks the plan's arrays and calls ``execute_csr_event_arrays``
           with a single-hook, single-event wrapper.  If it returns
           ``RESULT_STOP``, the event is aborted immediately.

        2. **Njit function** (``desc.njit_fn is not None``):
           Calls ``desc.njit_fn(population.state, population.config, deme_id)``.

        3. **Python wrapper** (``desc.py_wrapper is not None`` and no njit_fn):
           Calls the wrapper with the population object or state/config
           depending on its signature (1 param = population-level,
           3 params = state/config/deme_id).

        Returns:
            ``RESULT_CONTINUE`` or ``RESULT_STOP``.
        """
        if event_id < 0 or event_id >= NUM_EVENTS:
            return RESULT_CONTINUE

        ind_count = population.state.individual_count

        # ---- Resolve runtime state flags ----
        sperm_store = getattr(population.state, "sperm_storage", None)
        has_sperm_storage = sperm_store is not None and sperm_store.size > 0
        if not has_sperm_storage:
            # Discrete-generation or male-only — use a dummy.
            sperm_store = np.zeros((0, 0, 0), dtype=np.float64)
        assert sperm_store is not None
        stochastic = bool(getattr(getattr(population, "_config", None), "stochastic", False))
        continuous_sampling = bool(
            getattr(getattr(population, "_config", None), "continuous_sampling", False)
        )

        from ..numba_utils import NUMBA_ENABLED

        # Descriptors are pre-sorted by priority in from_compiled_hooks.
        # This loop is the ONLY place where CSR, njit, and py_wrapper
        # hooks are interleaved by priority in the Python fallback path.
        for desc in self.hooks_by_event.get(event_id, []):
            # ---- Deme guard (Python path) ----
            if not deme_selector_matches(desc.deme_selector, deme_id):
                continue

            # ---- CSR: declarative Op.* ----
            if desc.plan is not None:
                # Wrap the single plan as a 1-event, 1-hook CSR program.
                result = execute_csr_event_arrays(
                    np.int32(1),                          # n_events
                    np.int32(1),                          # n_hooks
                    np.array([0, 1], dtype=np.int32),     # hook_offsets
                    np.array([desc.plan.n_ops], dtype=np.int32),  # n_ops_list
                    np.array([0, desc.plan.n_ops], dtype=np.int32),  # op_offsets
                    desc.plan.op_types,
                    desc.plan.gidx_offsets,
                    desc.plan.gidx_data,
                    desc.plan.age_offsets,
                    desc.plan.age_data,
                    desc.plan.sex_masks.flatten(),
                    desc.plan.params,
                    desc.plan.condition_offsets,
                    desc.plan.condition_types,
                    desc.plan.condition_params,
                    np.array([0], dtype=np.int32),        # selector type: ANY
                    np.array([0, 0], dtype=np.int32),     # selector offsets
                    np.array([], dtype=np.int32),         # selector data
                    0,                                     # event_id (always 0 in wrapper)
                    ind_count,
                    sperm_store,
                    has_sperm_storage,
                    tick,
                    stochastic,
                    continuous_sampling,
                    deme_id,
                )
                if result == RESULT_STOP:
                    return RESULT_STOP

            # ---- Njit: compiled custom/selector hook ----
            if desc.njit_fn is not None:
                try:
                    result = desc.njit_fn(population.state, population.config, deme_id)
                    if result == RESULT_STOP:
                        return RESULT_STOP
                except Exception as e:
                    raise RuntimeError(f"Error in njit hook '{desc.name}': {e}") from e

            # ---- Python wrapper: pure-Python hook (Numba off) ----
            if desc.py_wrapper is not None and desc.njit_fn is None:
                if NUMBA_ENABLED:
                    # Safety: py_wrapper should never reach here with Numba on.
                    raise RuntimeError(
                        f"Python py_wrapper hook '{desc.name}' is not allowed when Numba is enabled."
                    )
                try:
                    import inspect

                    sig = inspect.signature(desc.py_wrapper)
                    params = list(sig.parameters.values())
                    if len(params) == 1:
                        # Single-parameter → population-level hook (legacy).
                        desc.py_wrapper(population)
                    else:
                        # Multi-parameter → (state, config, deme_id).
                        desc.py_wrapper(population.state, population.config, deme_id)
                except Exception as e:
                    raise RuntimeError(f"Error in py_wrapper hook '{desc.name}': {e}") from e

        return RESULT_CONTINUE

    def get_hooks_for_event(self, event_id: int) -> List[CompiledHookDescriptor]:
        """Return all descriptors registered for *event_id*, sorted by priority."""
        return self.hooks_by_event.get(event_id, [])
