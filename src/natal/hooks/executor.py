"""CSR execution engine and Python-level hook executor.

This module is the runtime heart of the hook system. It provides two
dispatch paths for declarative (CSR) and custom hooks:

**Numba fast path (compiled kernel)**
  ``execute_csr_event_arrays`` and ``_execute_single_csr_hook`` operate
  on flattened ``HookProgram`` arrays. The lifecycle templates
  (``engine/templates/*.tmpl.py``) call these directly, or call unified
  dispatch functions generated by ``compiler.compile_unified_event_hook``
  when CSR and njit hooks are mixed.

**Python fallback path (``HookExecutor``)**
  Used when Numba is disabled. Descriptors are sorted by ``priority``
  and executed sequentially — CSR ops via ``execute_csr_event_arrays``,
  njit functions by direct call, and py_wrapper functions by callable
  invocation.

----
Return value protocol
----
Every hook execution function returns an ``int`` following this convention:

  ``RESULT_CONTINUE`` (0)
      All operations completed successfully; proceed to the next hook.
  ``RESULT_SKIP`` (0, alias for readability)
      This hook is not applicable in the current context (e.g. wrong
      deme, out-of-bounds index).  Callers treat it identically to
      ``RESULT_CONTINUE`` — the distinction is for human readers only.
  ``RESULT_STOP`` (1)
      A ``stop_if_*`` operation triggered or the hook signalled an abort.
      The current *event* is immediately terminated; subsequent hooks
      for the same event are skipped. The next event (e.g. ``early``
      after ``first``) still executes normally.

----
Data structures in play
----

``HookProgram`` (NamedTuple)
    All declarative hooks packed into flat CSR arrays.  Three-level
    indexing: event → hook → op.  ``hook_offsets[event_id]`` gives the
    hook range; ``op_offsets[hook_idx]`` gives the op range.

``CompiledHookPlan`` (dataclass)
    A single declarative hook's ops, already resolved to concrete
    integer indices.  Stored as a ``plan`` field on
    ``CompiledHookDescriptor``.

``CompiledHookDescriptor`` (dataclass)
    One descriptor per registered hook.  Exactly one of ``plan``
    (CSR), ``njit_fn`` (compiled custom), or ``py_wrapper`` (Python)
    is the active payload.

----
Sperm storage awareness
----
Age-structured populations carry a ``sperm_storage`` array.  When a
female count is reduced (e.g. by ``Op.scale`` or ``Op.kill``), the
sperm categories must be scaled by the same survival rate to remain
coherent.  Discrete-generation populations have no sperm storage
(``has_sperm_storage=False``) and all operations use the simpler
``_apply_target_without_sperm`` path.

----
The hot loop is intentionally array-driven and avoids Python objects.
"""

